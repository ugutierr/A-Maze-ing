def _runs(raw: str) -> tuple[tuple[int, int, int], ...]:
    """Convert a glyph into horizontal runs (row, start, length)."""
    runs: list[tuple[int, int, int]] = []
    for row in range(GLYPH_HEIGHT):
        bits = int(raw[row * 3:row * 3 + 3], 16)
        column = 0
        while column < GLYPH_WIDTH:
            if not bits >> (GLYPH_WIDTH - 1 - column) & 1:
                column += 1
                continue
            start = column
            while column < GLYPH_WIDTH and bits >> (
                GLYPH_WIDTH - 1 - column
            ) & 1:
                column += 1
            runs.append((row, start, column - start))
    return tuple(runs)


_GLYPHS: tuple[tuple[tuple[int, int, int], ...], ...] = tuple(
    _runs(raw) for raw in _ROWS
)


def draw_text(
    surface: Surface,
    x: int,
    baseline_y: int,
    text: str,
    color: int,
    scale: float = 1.0,
) -> None:
    """Draw ``text`` on ``surface``, optionally enlarged.

    Args:
        surface: Destination image.
        x: Left coordinate of the first character.
        baseline_y: Baseline coordinate, as ``mlx_string_put`` expects.
        text: Text to draw. Characters outside ASCII are drawn as ``?``.
        color: Colour as 0xRRGGBB.
        scale: Size factor. 1.0 gives 10x19 pixel characters, 2.0 doubles
            them, and so on.
    """
    scale = max(scale, 0.5)
    pixel = surface.pixel_bytes(color)
    bpp = surface.bytes_per_pixel
    top = baseline_y - round(ASCENT * scale)
    fallback = _GLYPHS[ord("?") - FIRST_CHAR]

    for index, char in enumerate(text):
        position = ord(char) - FIRST_CHAR
        glyph = _GLYPHS[position] if 0 <= position < len(_GLYPHS) else fallback
        left = x + round(index * GLYPH_WIDTH * scale)

        for row, start, length in glyph:
            x0 = max(0, left + round(start * scale))
            x1 = min(surface.width, left + round((start + length) * scale))
            if x0 >= x1:
                continue
            y0 = top + round(row * scale)
            y1 = top + round((row + 1) * scale)
            for y in range(max(0, y0), min(surface.height, y1)):
                offset = y * surface.size_line + x0 * bpp
                surface.buffer[offset:offset + (x1 - x0) * bpp] = (
                    pixel * (x1 - x0)
                )
